const {chromium}=require('playwright');
const http=require('node:http'),https=require('node:https'),net=require('node:net');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict'),cp=require('node:child_process');
const policy=JSON.parse(fs.readFileSync(path.join(__dirname,'../work/browser-policy.json'),'utf8'));
const template=fs.readFileSync(path.join(__dirname,'../source/PortalTemplate.js'),'utf8')
 .replace('  /*CAMPUS_ACCOUNT*/',fs.readFileSync(path.join(__dirname,'../source/PortalAccount.js'),'utf8').trimEnd());
(async()=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'campus-http-policy-'));
 let tlsServer,proxy,browser;
 try{
  const gitOpenSSL=path.join(process.env.ProgramFiles||'C:\\Program Files','Git','usr','bin','openssl.exe');
  const openssl=process.env.YE_OPENSSL || (process.platform==='win32'&&fs.existsSync(gitOpenSSL)?gitOpenSSL:'openssl');
  cp.execFileSync(openssl,['req','-x509','-newkey','rsa:2048','-nodes','-keyout',path.join(temp,'key.pem'),'-out',path.join(temp,'cert.pem'),'-subj','/CN=tls-test.invalid','-days','1'],{stdio:'ignore'});
  tlsServer=https.createServer({key:fs.readFileSync(path.join(temp,'key.pem')),cert:fs.readFileSync(path.join(temp,'cert.pem'))},(_q,r)=>r.end('test-only self-signed endpoint'));
  await new Promise(resolve=>tlsServer.listen(0,'127.0.0.1',resolve));
  const requests=[],connects=[];
  proxy=http.createServer((q,r)=>{
   requests.push(q.url);
   if(q.url==='http://entry.gateway.test/entry'){r.writeHead(302,{Location:'http://login.school.test/form'});r.end();return;}
   r.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});
   r.end('<input name=username><input type=password><button type=button onclick="window.clicks=(window.clicks||0)+1">登录</button>');
  });
  proxy.on('connect',(req,socket,head)=>{
   connects.push(req.url);
   if(req.url!=='tls-test.invalid:443'){socket.end('HTTP/1.1 502 Bad Gateway\r\nContent-Length: 0\r\n\r\n');return;}
   const upstream=net.connect(tlsServer.address().port,'127.0.0.1',()=>{socket.write('HTTP/1.1 200 Connection Established\r\n\r\n');if(head.length)upstream.write(head);upstream.pipe(socket);socket.pipe(upstream);});
   upstream.on('error',()=>socket.destroy());socket.on('error',()=>upstream.destroy());socket.on('close',()=>upstream.destroy());
  });
  await new Promise(resolve=>proxy.listen(0,'127.0.0.1',resolve));
  // Remove only the no-proxy routing switch for this loopback-only fixture. The
  // actual production HTTPS compatibility switches are generated by C# above.
  const featureArgs=policy.arguments.filter(x=>x!=='--no-proxy-server');
  browser=await chromium.launch({ignoreDefaultArgs:true,args:['--headless=new','--no-sandbox','--remote-debugging-pipe','--disable-background-networking','--proxy-server=http://127.0.0.1:'+proxy.address().port,...featureArgs]});
  const page=await browser.newPage({ignoreHTTPSErrors:false});
  await page.goto('http://entry.gateway.test/entry');
  assert.equal(page.url(),'http://login.school.test/form');
  assert.equal(await page.locator('input[type=password]').count(),1);
  const script=template.replace('/*CAMPUS_CONFIG*/',JSON.stringify({origin:'http://login.school.test',username:'fixture-user',password:'fixture-secret',submit:true,serviceOption:''}));
  assert.equal(await page.evaluate(script),'submitted');
  assert.equal(await page.locator('[name=username]').inputValue(),'fixture-user');
  assert.equal(await page.evaluate(()=>clicks),1);
  assert.equal(connects.length,0,'HTTP login never attempted a forced HTTPS CONNECT');
  assert(requests.includes('http://entry.gateway.test/entry')&&requests.includes('http://login.school.test/form'));
  let rejected=false;
  try{await page.goto('https://tls-test.invalid/',{timeout:10000});}catch(e){rejected=/ERR_CERT_/.test(e.message);}
  assert(rejected,'self-signed HTTPS is still rejected by ordinary certificate validation');
  console.log('PASS: production browser flags, HTTP-only cross-host redirect, visible form, auto-fill/click, no HTTPS upgrade attempt, and rejection of an untrusted HTTPS certificate. Native Edge InPrivate dialog must be verified on Windows.');
 }finally{
  if(browser)await browser.close();
  if(proxy)await new Promise(resolve=>proxy.close(resolve));
  if(tlsServer)await new Promise(resolve=>tlsServer.close(resolve));
  fs.rmSync(temp,{recursive:true,force:true});
 }
})().catch(error=>{console.error(error);process.exitCode=1});
